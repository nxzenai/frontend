export interface Dataset {

    //////////////////////////////////////////////////////////
    // Identity
    //////////////////////////////////////////////////////////

    id: string;

    owner_id: string;

    //////////////////////////////////////////////////////////
    // File Information
    //////////////////////////////////////////////////////////

    filename: string;

    original_filename: string;

    extension: string;

    path: string;

    size: number;

    //////////////////////////////////////////////////////////
    // Statistics
    //////////////////////////////////////////////////////////

    rows: number;

    columns: number;

    missing_values: number;

    memory_usage: string;

    //////////////////////////////////////////////////////////
    // Metadata
    //////////////////////////////////////////////////////////

    column_names: string[];

    dtypes: Record<
        string,
        string
    >;

    target_column?: string;

    description?: string;

    tags: string[];

    //////////////////////////////////////////////////////////
    // Preview
    //////////////////////////////////////////////////////////

    preview: Record<
        string,
        any
    >[];

    //////////////////////////////////////////////////////////
    // Audit
    //////////////////////////////////////////////////////////

    created_at: string;

    updated_at: string;
}

////////////////////////////////////////////////////////////
// Upload Response
////////////////////////////////////////////////////////////

export interface DatasetUploadResponse {

    id: string;

    filename: string;

    original_filename: string;

    extension: string;

    size: number;

    uploaded_at: string;
}

////////////////////////////////////////////////////////////
// Dataset Summary
////////////////////////////////////////////////////////////

export interface DatasetSummary {

    rows: number;

    columns: number;

    missing_values: number;

    memory_usage: string;

    file_size: number;

    column_names: string[];

    dtypes: Record<
        string,
        string
    >;
}

////////////////////////////////////////////////////////////
// Dataset Preview
////////////////////////////////////////////////////////////

export interface DatasetPreview {

    columns: string[];

    rows: Record<
        string,
        any
    >[];

    total_rows: number;

    preview_rows: number;
}

////////////////////////////////////////////////////////////
// Dataset List Response
////////////////////////////////////////////////////////////

export interface DatasetListResponse {

    items: Dataset[];

    page: number;

    limit: number;

    total: number;

    pages: number;
}